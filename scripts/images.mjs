/**
 * Converts photos and cut-out products from assets-src/ into responsive
 * AVIF + WebP files in public/img/ and writes their manifest to lib/images.ts.
 * Unchanged sources are skipped; pass --force to rebuild everything.
 */
import { mkdir, readdir, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const SRC = "assets-src";
const OUT = "public/img";
const MANIFEST = "lib/images.ts";
const WIDTHS = [640, 1280, 1920];
const FORMATS = {
  avif: { quality: 55, effort: 6 },
  webp: { quality: 78, effort: 5 },
};
const force = process.argv.includes("--force");

async function listSources(dir) {
  const entries = await readdir(dir, { withFileTypes: true, recursive: true });
  return entries
    .filter((e) => e.isFile() && /\.(png|jpe?g)$/i.test(e.name))
    .map((e) => path.join(e.parentPath, e.name))
    .sort();
}

/** Target widths that do not upscale; a smaller source keeps its own width as the largest step. */
function widthsFor(sourceWidth) {
  const widths = WIDTHS.filter((w) => w < sourceWidth);
  widths.push(Math.min(sourceWidth, WIDTHS.at(-1)));
  return widths;
}

async function isFresh(output, sourceMtime) {
  try {
    return (await stat(output)).mtimeMs >= sourceMtime;
  } catch {
    return false;
  }
}

async function convert(file) {
  const key = path
    .relative(SRC, file)
    .replace(/\\/g, "/")
    .replace(/\.[^.]+$/, "");
  const meta = await sharp(file).metadata();
  const alpha = Boolean(meta.hasAlpha);
  const sourceMtime = (await stat(file)).mtimeMs;
  const outDir = path.join(OUT, path.dirname(key));
  await mkdir(outDir, { recursive: true });

  const sources = { avif: [], webp: [] };
  let written = 0;
  for (const width of widthsFor(meta.width)) {
    const height = Math.round((meta.height * width) / meta.width);
    for (const [format, options] of Object.entries(FORMATS)) {
      const name = `${path.basename(key)}-${width}.${format}`;
      const output = path.join(outDir, name);
      if (force || !(await isFresh(output, sourceMtime))) {
        await sharp(file)
          .resize({ width })
          [format]({ ...options, ...(alpha && format === "webp" ? { alphaQuality: 90 } : {}) })
          .toFile(output);
        written++;
      }
      sources[format].push({ width, height, src: `/img/${path.dirname(key)}/${name}`.replace("/./", "/") });
    }
  }
  return { key, width: meta.width, height: meta.height, alpha, sources, written };
}

function manifestSource(entries) {
  const body = entries
    .map(({ key, width, height, alpha, sources }) => {
      const list = (items) =>
        items.map((s) => `{ width: ${s.width}, height: ${s.height}, src: "${s.src}" }`).join(", ");
      return [
        `  "${key}": {`,
        `    width: ${width},`,
        `    height: ${height},`,
        `    alpha: ${alpha},`,
        `    avif: [${list(sources.avif)}],`,
        `    webp: [${list(sources.webp)}],`,
        `  },`,
      ].join("\n");
    })
    .join("\n");

  return `// Generated by \`pnpm images\` from assets-src/. Do not edit by hand.

export type ImageSource = { width: number; height: number; src: string };

export type ImageAsset = {
  /** Width and height of the original file in pixels. */
  width: number;
  height: number;
  /** Transparent cut-out (products) rather than a photo. */
  alpha: boolean;
  /** Ascending by width. */
  avif: readonly ImageSource[];
  webp: readonly ImageSource[];
};

export const images = {
${body}
} as const satisfies Record<string, ImageAsset>;

export type ImageKey = keyof typeof images;

/** \`srcset\` attribute value for one format of an image. */
export function srcSet(key: ImageKey, format: "avif" | "webp"): string {
  return images[key][format].map((s) => \`\${s.src} \${s.width}w\`).join(", ");
}

/** Largest WebP file, used as the plain \`src\` fallback. */
export function fallbackSrc(key: ImageKey): string {
  return images[key].webp.at(-1)!.src;
}
`;
}

const files = await listSources(SRC);
if (force) await rm(OUT, { recursive: true, force: true });
const entries = [];
for (const file of files) {
  const entry = await convert(file);
  entries.push(entry);
  console.log(`${entry.key}  ${entry.width}×${entry.height}${entry.alpha ? "  alpha" : ""}  ${entry.written} written`);
}
await writeFile(MANIFEST, manifestSource(entries));
console.log(`${entries.length} images → ${OUT}, manifest → ${MANIFEST}`);
